package agent

import (
	"context"
	"fmt"
	"strings"

	"github.com/rjwashi/hackbot/internal/nmap"
)

// IssueCreator opens a tracking issue for a finding and returns its URL.
type IssueCreator interface {
	CreateIssue(ctx context.Context, repo, title, body string, labels []string) (string, error)
}

// DryRunIssueCreator logs what would be created without calling gh.
type DryRunIssueCreator struct {
	Log func(string)
}

// CreateIssue reports the issue that would have been created.
func (d DryRunIssueCreator) CreateIssue(_ context.Context, repo, title, body string, labels []string) (string, error) {
	msg := fmt.Sprintf("[dry-run] would create issue in %s: %q (labels: %s)", repo, title, strings.Join(labels, ","))
	if body != "" {
		msg += "\n" + body
	}
	if d.Log != nil {
		d.Log(msg)
	}
	return "", nil
}

// issueTitle formats a stable, dedupe-friendly issue title for a finding.
func issueTitle(f nmap.Finding) string {
	where := f.Host
	if f.Port > 0 {
		where = fmt.Sprintf("%s:%d/%s", f.Host, f.Port, f.Protocol)
	}
	return fmt.Sprintf("[nmap][%s] %s on %s", f.Severity, f.Title, where)
}

// issueBody renders a finding as a Markdown issue body.
func issueBody(f nmap.Finding) string {
	var b strings.Builder
	fmt.Fprintf(&b, "**Severity:** %s\n\n", f.Severity)
	fmt.Fprintf(&b, "**Host:** `%s`\n\n", f.Host)
	if f.Port > 0 {
		fmt.Fprintf(&b, "**Port:** `%d/%s`\n\n", f.Port, f.Protocol)
	}
	if f.Service != "" {
		fmt.Fprintf(&b, "**Service:** `%s`\n\n", f.Service)
	}
	fmt.Fprintf(&b, "**Finding:** %s\n\n", f.Title)
	fmt.Fprintf(&b, "**Detail:** %s\n\n", f.Detail)
	b.WriteString("---\n_Auto-generated by hackbot from an nmap scan. Verify before acting._\n")
	return b.String()
}
