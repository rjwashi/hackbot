// This file defines the "actions" stage: turning findings into GitHub issues.
// Issue creation is dry-run by default so an accidental run cannot spam a repo.
package agent // same package as the pipeline

import ( // imports for this file
	"context"                                  // pass through cancellation
	"fmt"                                      // Sprintf for titles/bodies
	"github.com/rjwashi/hackbot/internal/nmap" // Finding/Severity types
	"strings"                                  // Builder + Join for rendering Markdown
)

// IssueCreator opens a tracking issue for a finding and returns its URL.
type IssueCreator interface { // abstraction so tests can use a fake and production uses gh
	CreateIssue(ctx context.Context, repo, title, body string, labels []string) (string, error) // returns issue URL
}

// DryRunIssueCreator logs what would be created without calling gh.
type DryRunIssueCreator struct { // safe default so nothing is filed accidentally
	Log func(string) // optional sink (usually stderr); nil means "discard"
}

// CreateIssue reports the issue that would have been created.
func (d DryRunIssueCreator) CreateIssue(_ context.Context, repo, title, body string, labels []string) (string, error) { // no-op
	msg := fmt.Sprintf("[dry-run] would create issue in %s: %q (labels: %s)", repo, title, strings.Join(labels, ",")) // headline
	if body != "" {                                                                                                   // include the body so the operator can review what would be filed...
		msg += "\n" + body // ...appended below the headline
	}
	if d.Log != nil { // only call the sink if one was provided
		d.Log(msg) // emit the preview
	}
	return "", nil // empty URL signals "not actually created"
}

// issueTitle formats a stable, dedupe-friendly issue title for a finding.
func issueTitle(f nmap.Finding) string { // stable titles let GitHub dedupe/search by title
	where := f.Host // default label is the host...
	if f.Port > 0 { // ...but prefer host:port/proto when a port is involved
		where = fmt.Sprintf("%s:%d/%s", f.Host, f.Port, f.Protocol) // e.g. "1.2.3.4:6379/tcp"
	}
	return fmt.Sprintf("[nmap][%s] %s on %s", f.Severity, f.Title, where) // e.g. "[nmap][CRITICAL] Redis exposed on ..."
}

// issueBody renders a finding as a Markdown issue body.
func issueBody(f nmap.Finding) string { // humans read these, so make them structured
	var b strings.Builder                               // efficient string building
	fmt.Fprintf(&b, "**Severity:** %s\n\n", f.Severity) // bold severity line
	fmt.Fprintf(&b, "**Host:** `%s`\n\n", f.Host)       // host in code formatting
	if f.Port > 0 {                                     // include the port only for port-level findings...
		fmt.Fprintf(&b, "**Port:** `%d/%s`\n\n", f.Port, f.Protocol) // e.g. `6379/tcp`
	}
	if f.Service != "" { // include the service name when known
		fmt.Fprintf(&b, "**Service:** `%s`\n\n", f.Service)
	}
	fmt.Fprintf(&b, "**Finding:** %s\n\n", f.Title)                                              // the headline
	fmt.Fprintf(&b, "**Detail:** %s\n\n", f.Detail)                                              // why it matters + banner
	b.WriteString("---\n_Auto-generated by hackbot from an nmap scan. Verify before acting._\n") // attribution + caution
	return b.String()                                                                            // final Markdown
}
